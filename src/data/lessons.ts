export const lessons: Lesson[] = scenarios.flatMap((s) =>
  [0, 1].map((part) => {
    const batch = phrases
      .filter((p) => p.scenario === s.id)
      .slice(part * 4, part * 4 + 4);
    const targets = [batch[0], batch[3]];
    if (part === 0 && s.id !== "signs") targets[1] = batch[1];
    const steps: Step[] = batch.flatMap((p, i) => {
      const result: Step[] = [
        { id: `${p.id}-study`, type: "study", phraseId: p.id },
      ];
      if (i === 1 || i === 3) {
        const t = targets[i === 1 ? 0 : 1];
        result.push({
          id: `${t.id}-quiz-${part}-${i}`,
          type: s.id === "signs" ? "sign" : "quiz",
          phraseId: t.id,
          prompt:
            s.id === "signs"
              ? "Что написано на вывеске?"
              : questions[s.id][part * 2 + (i === 1 ? 0 : 1)],
          options: [
            t.id,
            ...batch
              .filter((q) => q.id !== t.id)
              .slice(0, 2)
              .map((q) => q.id),
          ],
          explanation: t.hint,
          speaker: dialogue[t.id]?.[0],
          speakerTranslation: dialogue[t.id]?.[1],
        });
      }
      return result;
    });
    if (s.id !== "signs") {
      // Keep the final step in place for resumable lessons, using a phrase
      // already introduced in this lesson instead of an unrelated sign.
      const recap = batch[2];
      steps.push({
        id: `${s.id}-${part}-recap`,
        type: "quiz",
        phraseId: recap.id,
        prompt: `Повторим: как сказать «${recap.ru}»?`,
        options: [recap.id, batch[0].id, batch[1].id],
        explanation: recap.hint,
      });
    }
    return {
      id: `${s.id}-${part + 1}`,
      scenarioId: s.id,
      title: part === 0 ? "Самое нужное" : "Ещё немного уверенности",
      part: part + 1,
      steps,
      letters: s.letters.slice(part * 2, part * 2 + 2),
    };
  }),
);
// Fix sign distractors to always provide three distinct choices.
for (const lesson of lessons)
  for (const step of lesson.steps)
    if (step.type === "sign")
      step.options = [
        step.phraseId,
        ...phrases
          .filter((p) => p.scenario === "signs" && p.id !== step.phraseId)
          .slice(0, 2)
          .map((p) => p.id),
      ];
